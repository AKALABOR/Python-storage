def оцінити_гравця():
    try:
        очки = int(input("Введіть кількість набраних очок (0-100): "))

        if очки < 0 or очки > 100:
            raise ValueError("Некоректне введення! Кількість очок повинна бути в межах від 0 до 100.")

        if очки < 50:
            рейтинг = "Початківець"
            множник = 1
        elif очки < 70:
            рейтинг = "Срібний гравець"
            множник = 1.5
        elif очки < 90:
            рейтинг = "Золотий гравець"
            множник = 2
        else:
            рейтинг = "Платиновий гравець"
            множник = 3

        фінальні_очки = очки * множник
        print(f"Ваш рейтинг: {рейтинг}. Фінальні очки: {фінальні_очки}")

    except ValueError as e:
        print(e)

оцінити_гравця()
